    public void irSend(View view) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.KITKAT) {
            try {
                irSend4Kitkat(view);
            } catch (Exception asd) {
                asd.printStackTrace();
            }
            Vibrator v = (Vibrator) getSystemService(Context.VIBRATOR_SERVICE);
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
                v.vibrate(VibrationEffect.createOneShot(100, VibrationEffect.DEFAULT_AMPLITUDE));
            } else {
                v.vibrate(100);
            }
        }
    }

    private void irSend4Kitkat(View view) {
        try {
            if (consumerIrManager.hasIrEmitter()) {
                String data = String.valueOf(irData.get(view.getId()));
                if (data != null) {
                    String values[] = data.split(",");
                    int[] pattern = new int[values.length - 1];

                    for (int i = 0; i < pattern.length; i++) {
                        pattern[i] = Integer.parseInt(values[i + 1]);
                    }
                    consumerIrManager.transmit(Integer.parseInt(values[0]), pattern);
                }
            } else {
                Log.e("LOG", "not supported options");
                alert_dialog();
            }

        } catch (NullPointerException asd) {
            Toast.makeText(this, "Some thing went wrong", Toast.LENGTH_LONG).show();
        } catch (Exception asd) {
            asd.printStackTrace();
        }
    }


